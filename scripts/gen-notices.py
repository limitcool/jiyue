"""Regenerate THIRD_PARTY_NOTICES.md at the repo root from `cargo metadata`.

Scope: crates reachable from the two shipped binaries (jiyue, jiyue-mcp) through
normal dependency edges (no dev or build-only edges). Conditional dependencies are
included unless their cfg clearly excludes Windows; each inclusion decision is
printed to stderr so it can be reviewed.

Run: python scripts/gen-notices.py (any Python 3; standard library only). installer/build.ps1 runs it.
Exit code 1 when a crate has an unknown licence or a copyleft term (GPL/LGPL/AGPL/
MPL-only/SSPL/proprietary), so the audit can be re-run in CI.
"""
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "THIRD_PARTY_NOTICES.md"
SHIPPED = ["jiyue", "jiyue-mcp"]
COPYLEFT = re.compile(r"\b(A|L|)GPL\b|\bSSPL\b|\bBUSL\b|proprietary|\bEUPL\b|\bMPL\b", re.I)
PERMISSIVE = re.compile(r"^(MIT|Apache-2\.0|BSD-\d-Clause|ISC|Zlib|Unlicense|CC0-1\.0|0BSD|Unicode-3\.0|BSL-1\.0|zlib-acknowledgement|MIT-0)", re.I)
NON_WINDOWS_OS = re.compile(
    r"\b(unix|linux|macos|apple|android|ios|wasm|wasi|uefi|hermit|redox|vxworks|espidf|"
    r"freebsd|netbsd|openbsd|dragonfly|solaris|illumos|fuchsia|haiku|emscripten|target_os|target_family)\b"
)


def licence_ok(lic):
    """True when at least one OR alternative is a permissive licence."""
    alts = [a.strip(" ()") for a in re.split(r"\s+OR\s+|/", lic)]
    return any(PERMISSIVE.match(a) for a in alts)


def cargo_metadata():
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1"],
        cwd=ROOT, capture_output=True, encoding="utf-8", check=True,
    ).stdout
    return json.loads(out)


def edge_included(dep_kinds, label, skipped, included_cond):
    normal = [k for k in dep_kinds if k.get("kind") is None]
    if not normal:
        return False
    targets = {k.get("target") for k in normal}
    if None in targets:
        return True
    for t in targets:
        low = t.lower()
        if "any()" in low or "fuzzing" in low:
            continue  # never compiled
        if "windows" in low and "not(windows" not in low:
            included_cond.add((label, t))
            return True
        if "not(" in low:
            included_cond.add((label, t))  # negated OS gate: keep, over-include
            return True
        if NON_WINDOWS_OS.search(low):
            continue
        included_cond.add((label, t))
        return True
    skipped.add(label)
    return False


def reachable(meta):
    pkgs = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    members = set(meta["workspace_members"])
    by_name = {}
    for pid in members:
        by_name[pkgs[pid]["name"]] = pid
    roots = [by_name[n] for n in SHIPPED if n in by_name]
    if len(roots) != len(SHIPPED):
        sys.exit(f"missing shipped package among {SHIPPED}")
    seen = set()
    stack = list(roots)
    skipped, cond = set(), set()
    while stack:
        pid = stack.pop()
        if pid in seen:
            continue
        seen.add(pid)
        for dep in nodes[pid]["deps"]:
            label = f"{pkgs[pid]['name']} -> {dep['name']}"
            if edge_included(dep["dep_kinds"], label, skipped, cond):
                stack.append(dep["pkg"])
    return seen, members, pkgs, cond, skipped


def main():
    meta = cargo_metadata()
    keep, members, pkgs, cond, skipped = reachable(meta)
    for label, t in sorted(cond):
        print(f"conditional kept: {label} [{t}]", file=sys.stderr)
    for label in sorted(skipped):
        print(f"excluded (non-Windows only): {label}", file=sys.stderr)

    rows, flagged = [], []
    for pid in sorted(keep, key=lambda i: (pkgs[i]["name"], pkgs[i]["version"])):
        if pid in members:
            continue
        p = pkgs[pid]
        lic = p.get("license") or ""
        if not lic:
            lic = "UNKNOWN (license_file: %s)" % (p.get("license_file") or "none")
        repo = p.get("repository") or p.get("homepage") or ""
        rows.append((p["name"], p["version"], lic, repo))
        if lic.startswith("UNKNOWN") or (COPYLEFT.search(lic) and not licence_ok(lic)):
            flagged.append((p["name"], p["version"], lic))

    lines = [
        "# Third-party notices",
        "",
        "Jiyue (霁月) is licensed under MIT OR Apache-2.0 (see LICENSE-MIT and LICENSE-APACHE).",
        "This file lists the third-party software linked into `jiyue.exe` and `jiyue-mcp.exe`",
        "and the bundled assets. It is generated by `scripts/gen-notices.py` from `cargo metadata`;",
        "do not edit it by hand.",
        "",
        "Where a crate offers a choice (`A OR B`) the notice lists the expression; Jiyue uses the",
        "permissive option. Where a crate has `MPL-2.0` only as one of several OR options, the",
        "MPL-2.0 option is not used.",
        "",
        "## Bundled assets",
        "",
        "| Asset | Where | Licence |",
        "| --- | --- | --- |",
        "| Tabler Icons (SVG subset, 56 files) | `crates/jiyue-app/assets/icons/` | MIT. Copyright (c) Paweł Kuna. |",
        "| Application logo and icon | `crates/jiyue-app/assets/logo/` | Original work of the project, MIT OR Apache-2.0. |",
        "",
        "The application does not bundle any font file. It uses fonts installed on the system by family",
        "name (Noto Sans SC, Noto Serif SC, JetBrainsMono Nerd Font).",
        "",
        "## Crates",
        "",
        f"{len(rows)} crates. Workspace crates are excluded (they are Jiyue itself).",
        "",
        "| Crate | Version | Licence | Repository |",
        "| --- | --- | --- | --- |",
    ]
    for name, ver, lic, repo in rows:
        lines.append(f"| {name} | {ver} | {lic.replace('|', '/')} | {repo} |")
    lines += [
        "",
        "## Licence texts",
        "",
        "The full texts of MIT and Apache-2.0 are in LICENSE-MIT and LICENSE-APACHE at the repository root.",
        "Crates under other licences (Unicode-3.0, BSD-2/3-Clause, Zlib, ISC, CC0-1.0, BSL-1.0, LLVM exception)",
        "require their copyright notice to be kept; the source packages in the cargo registry carry them.",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {OUT} with {len(rows)} crates", file=sys.stderr)
    if flagged:
        print("FLAGGED:", file=sys.stderr)
        for f in flagged:
            print("  ", *f, file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
